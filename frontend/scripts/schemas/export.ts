/**
 * Writes the document schemas of shared/documents.ts as JSON Schema, one file
 * per collection, and from them the pipelines' pydantic models:
 *
 *   npm run schemas            # both
 *   npm run schemas -- --json  # JSON Schema only (no uv needed)
 *
 * shared/documents/json/<collection>.schema.json and
 * data/pipelines/src/entities/documents/ are generated; edit
 * shared/documents.ts and run this again.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { z } from "zod/v4";
import { documentSchemas } from "../../shared/documents";

const root = resolve(import.meta.dirname, "../..");
const jsonDir = join(root, "shared/documents/json");
mkdirSync(jsonDir, { recursive: true });

const titles: Record<string, string> = {
  nodes: "NodeDocument",
  edges: "EdgeDocument",
  revisions: "RevisionDocument",
  votes: "VoteDocument",
  notes: "NoteDocument",
  extractions: "ExtractionDocument",
  audit: "AuditDocument",
  articlePages: "ArticlePageDocument",
};

const files: string[] = [];
for (const [collection, schema] of Object.entries(documentSchemas)) {
  const json = {
    title: titles[collection],
    ...z.toJSONSchema(schema, { io: "input", unrepresentable: "any" }),
  };
  const file = join(jsonDir, `${collection}.schema.json`);
  writeFileSync(file, JSON.stringify(json, null, 2) + "\n");
  files.push(file);
}
console.log(`wrote ${files.length} JSON Schemas to ${jsonDir}`);

if (!process.argv.includes("--json")) {
  const output = join(root, "../data/pipelines/src/entities/documents");
  // Pinned, run by uv in its own environment: the pipelines' lockfile is not
  // touched by a generator they do not import.
  execFileSync(
    "uvx",
    [
      "--from",
      "datamodel-code-generator==0.34.0",
      "datamodel-codegen",
      "--input",
      jsonDir,
      "--input-file-type",
      "jsonschema",
      "--output",
      output,
      "--output-model-type",
      "pydantic_v2.BaseModel",
      "--target-python-version",
      "3.12",
      "--use-annotated",
      "--use-title-as-name",
      "--use-standard-collections",
      "--use-union-operator",
      "--allow-extra-fields",
      "--disable-timestamp",
      "--custom-file-header",
      "# Generated by `npm run schemas` (frontend/scripts/schemas/export.ts)\n# from frontend/shared/documents.ts. Do not edit.",
    ],
    { stdio: "inherit" },
  );
  console.log(`wrote ${output}`);
}
